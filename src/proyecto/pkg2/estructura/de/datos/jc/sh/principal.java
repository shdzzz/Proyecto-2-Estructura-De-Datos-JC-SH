	/**
	 * Metodo Necesario para mostrar los documentos en el jTable1 sin este
	 * solo se guardaria el documento en memoria
	 *
	 * @param user por cada usuario tiene sus documentos
	 */
	public void actualizarTablaDocumentos(Usuario user) {
		DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
		modelo.setRowCount(0);

		if (user == null) {
			return;
		}

		NodoDocumento actual = user.getPrimerDocumento();

		while (actual != null) {
			String estado = actual.isEnCola() ? "En Cola" : "Pendiente";

			modelo.addRow(new Object[]{
				actual.getNombre(),
				actual.getTamaño(),
				actual.getTipo(),
				estado
			});

			actual = actual.getSiguiente();
		}
	}

	private String[][] recolectarDatos() {
		/**
		 * Recolecta los datos de los usuarios desde la lista de la GUI.
		 * Extrae el nombre y tipo de cada usuario para ser guardados en archivo.
		 * 
		 * @return Matriz de String [n][2] donde [n][0] es nombre y [n][1] es tipo
		 */
		javax.swing.ListModel modelo = ListadeUsuarios.getModel();
		int cantidad = modelo.getSize();
		String[][] matriz = new String[cantidad][2];
		for (int i = 0; i < cantidad; i++) {
			String textoFila = modelo.getElementAt(i).toString();
			int posicionParentesis = textoFila.indexOf(" (");

			if (posicionParentesis != -1) {
				matriz[i][0] = textoFila.substring(0, posicionParentesis).trim();
				String tipo = textoFila.substring(posicionParentesis + 2);
				matriz[i][1] = tipo.replace(")", "").trim();
			} else {
				matriz[i][0] = textoFila.trim();
				matriz[i][1] = "normal";
			}
		}

		return matriz;
	}

	/**
	 * Metodo responsabel de actualizar la vista de lista este metodo se
	 * usara cada vez que el usario agrgue un documento a la cola de
	 * impresion.
	 * 
	 * Muestra la cola de impresión como una secuencia ordenada por prioridad.
	 * Incluye información de tiempo actual, cantidad de documentos y leyenda.
	 */
	public void actualizarVistaLista() {

		VistaLista.setText("");

		if (MiMonticulo.estaVacio()) {
			VistaLista.setText(" > La cola está vacía."); // notifica si la cola esta vacia
			return;
		}

		//diseño: 
		StringBuilder sb = new StringBuilder();
		sb.append("========== COLA DE IMPRESIÓN ==========\n");
		sb.append("Tiempo actual: ").append(miReloj.getTiempoActual()).append("\n");
		sb.append("Documentos en cola: ").append(MiMonticulo.getTamaño()).append("\n");
		sb.append("==========================================\n");
		sb.append(String.format("%-3s | %-20s | %-8s | %-10s | %-8s\n",
			"#", "Documento", "Usuario", "Prioridad", "Tamaño"));
		sb.append("------------------------------------------\n");

		// agrega de manera de lista los procesos ordenados por prioridad
		for (int i = 0; i < MiMonticulo.getTamaño(); i++) {
			NodoDocumento doc = MiMonticulo.getNodo(i);
			if (doc != null) {
				String posicion = (i == 0) ? "*" + (i + 1) : " " + (i + 1);
				String nombreTruncado = truncarNombre(doc.getNombre(), 18);
				String nombreUsuario = (doc.getNombreUsuario() == null) ? "---" : doc.getNombreUsuario();
				String usuarioTruncado = truncarNombre(nombreUsuario, 7);

				sb.append(String.format("%-3s | %-20s | %-8s | %-10d | %-8d\n",
					posicion, // Posición en la cola (con * para el primero)
					nombreTruncado, // Nombre del documento
					usuarioTruncado, // Usuario
					doc.getClaveOrdenacion(), // Prioridad calculada
					doc.getTamaño()));            // Tamaño en páginas
			}
		}

		sb.append("\n==========================================\n");
		sb.append("* = Siguiente documento a imprimir\n");
		sb.append("Prioridad: menor valor = mayor prioridad");

		VistaLista.setText(sb.toString());
	}

	/**
	 * Metodo responsable de actualizar la vista de arbol este metodo se
	 * aplicara cada vez que el usario agregue un documento a la cola de
	 * impresion.
	 * 
	 * Muestra la cola de impresión como una estructura jerárquica (min-heap).
	 * Incluye información de tiempo actual, cantidad de documentos y leyenda.
	 * Resalta la raíz como el siguiente documento a imprimir.
	 */
	public void actualizarVistaArbol() {
		VistaArbol.setText(""); // Limpiar JTextArea

		// IMPORTANTE: Forzar fuente Monospaced por código si no lo hiciste en el diseño
		VistaArbol.setFont(new java.awt.Font("Monospaced", 0, 11));

		int n = MiMonticulo.getTamaño();

		if (n == 0) {
			VistaArbol.setText("\n   [ La cola de impresión está vacía ]");
			return;
		}

		StringBuilder sb = new StringBuilder();
		sb.append("      === ESTRUCTURA JERÁRQUICA (MIN-HEAP) ===\n");
		sb.append("==================================================\n");
		sb.append("Tiempo actual: ").append(miReloj.getTiempoActual()).append("\n");
		sb.append("Documentos en cola: ").append(n).append("\n");
		sb.append("==================================================\n\n");

		// Calculamos la altura del árbol
		int altura = (int) (Math.log(n) / Math.log(2)) + 1;

		// Variables para controlar el espaciado
		int anchoNodo = 25; // Ancho ampliado para mostrar nombres completos "[nombre_largo (P:XXXXX)]"
		int separation = 2; // Espacio reducido entre hermanos para compensar

		// El ancho del último nivel determina el espaciado base
		int maxNodosUltimoNivel = (int) Math.pow(2, altura - 1);
		int anchoNivelBase = maxNodosUltimoNivel * (anchoNodo + separation);

		// Margen izquierdo base para separar del borde del TextArea
		String margenIzquierdoBase = "    ";

		int indiceActual = 0;
		int nodosEnNivel = 1;

		for (int nivel = 0; nivel < altura; nivel++) {
			// Añadir margen izquierdo base
			sb.append(margenIzquierdoBase);

			// Calcular el espaciado antes del primer nodo y entre nodos para este nivel
			int espacioNivel = anchoNivelBase / nodosEnNivel;
			int espacioInicial = (espacioNivel / 2) - (anchoNodo / 2);

			// 1. Espacios iniciales del nivel (sangría de pirámide)
			for (int e = 0; e < espacioInicial; e++) {
				sb.append(" ");
			}

			// 2. Imprimir los nodos de este nivel
			for (int i = 0; i < nodosEnNivel && indiceActual < n; i++) {
				NodoDocumento doc = MiMonticulo.getNodo(indiceActual);

				// Formatear el texto del nodo "[nombre (P:X)]"
				// Mostramos el nombre completo sin truncar
				String textoNodo = "[" + doc.getNombre() + " (P:" + doc.getClaveOrdenacion() + ")]";

				// Resaltar la raíz (primer elemento) con un asterisco
				if (indiceActual == 0) {
					textoNodo = "*" + textoNodo + "*";
				}

				// Centrar el texto del nodo en el espacio de 'anchoNodo'
				sb.append(centrarTexto(textoNodo, anchoNodo));

				// Espacio entre nodos del mismo nivel (hermanos y primos)
				if (i < nodosEnNivel - 1) {
					for (int e = 0; e < espacioNivel - anchoNodo; e++) {
						sb.append(" ");
					}
				}

				indiceActual++;
			}

			// 3. Salto de línea para el siguiente nivel
			sb.append("\n\n");

			// El siguiente nivel tiene el doble de nodos
			nodosEnNivel *= 2;
		}

		// Añadir leyenda al final
		sb.append("\n==================================================\n");
		sb.append("Leyenda: *nodo* = Siguiente documento a imprimir (raíz)\n");
		sb.append("P:X = Prioridad calculada (menor = mayor prioridad)");

		VistaArbol.setText(sb.toString());
	}

	/**
	 * Método auxiliar para centrar texto en la vista de árbol.
	 * Calcula y distribuye espacios para centrar el texto dentro de un ancho determinado.
	 * 
	 * @param texto Texto a centrar
	 * @param longitud Longitud total del espacio disponible
	 * @return Texto centrado con espacios a izquierda y derecha
	 */
	private String centrarTexto(String texto, int longitud) {
		if (texto.length() >= longitud) {
			return texto.substring(0, longitud);
		}
		int espaciosTotal = longitud - texto.length();
		int espaciosIzq = espaciosTotal / 2;
		int espaciosDer = espaciosTotal - espaciosIzq;

		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < espaciosIzq; i++) {
			sb.append(" ");
		}
		sb.append(texto);
		for (int i = 0; i < espaciosDer; i++) {
			sb.append(" ");
		}
		return sb.toString();
	}

	/**
	 * Método auxiliar para truncar nombres largos en la vista de lista.
	 * Asegura que los nombres no desborden el formato de la tabla.
	 * 
	 * @param nombre Nombre original a truncar
	 * @param longitudMax Longitud máxima permitida
	 * @return Nombre truncado con punto suspensivo si excede el límite
	 */
	private String truncarNombre(String nombre, int longitudMax) {
		if (nombre.length() > longitudMax) {
			return nombre.substring(0, longitudMax - 1) + ".";
		}
		return nombre;
	}

